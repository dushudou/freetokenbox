"""Render the existing square-hole coin mark as a crawlable social preview."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import base64
root = Path(__file__).resolve().parents[1]
im = Image.new('RGB', (1200,630), '#18181b'); d=ImageDraw.Draw(im)
font='/System/Library/Fonts/Supplemental/Arial.ttf'
d.rounded_rectangle((88,84,202,198),radius=28,fill='#10b981')
d.ellipse((112,108,178,174),fill='white'); d.rounded_rectangle((131,127,159,155),radius=5,fill='#10b981')
d.text((88,263),'FreeTokenBox',font=ImageFont.truetype(font,76),fill='#fafafa')
d.text((90,365),'AI APIs, trials & compute',font=ImageFont.truetype(font,36),fill='#a1a1aa')
d.line((90,454,1110,454),fill='#3f3f46',width=1)
d.text((90,497),'Official sources   /   Clear quotas   /   Practical guides',font=ImageFont.truetype(font,25),fill='#6ee7b7')
path=root/'public/og.png'; im.save(path,optimize=True)
(root/'src/og-image.js').write_text("// Generated by scripts/generate-og.py\nexport const OG_IMAGE_BASE64 = '"+base64.b64encode(path.read_bytes()).decode()+"'\n")
print(path, path.stat().st_size)
