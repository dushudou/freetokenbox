import fs from 'node:fs'
const base = JSON.parse(fs.readFileSync(new URL('../content/reviews.json', import.meta.url),'utf8'))
const dir = new URL('../content/', import.meta.url)
const entries = fs.readdirSync(dir).filter(f => /^media-.*-resources\.json$/.test(f)).sort().flatMap(f => JSON.parse(fs.readFileSync(new URL(f,dir),'utf8')))
const seen = new Set()
for (const r of entries) {
 if (!/^[a-z0-9-]+$/.test(r.slug) || seen.has(r.slug)) throw Error('Invalid or duplicate slug: '+r.slug)
 seen.add(r.slug)
 for (const key of ['name','description','content','provider','url','category','source','checked']) if (!r[key]) throw Error(`${r.slug}: missing ${key}`)
 if (r.status !== 'verified' || !r.en?.content || !r.en?.name || !r.en?.description) throw Error('Missing review/translation: '+r.slug)
 for (const url of [r.url,r.source]) if (!url.startsWith('https://')) throw Error('Official HTTPS URL required')
}
const reviews = {...base, ...Object.fromEntries(entries.map(r => [r.slug,r]))}
fs.writeFileSync(new URL('../src/media-resources.js',import.meta.url),'// Generated by scripts/build-reviewed-content.mjs; edit content/media-*-resources.json.\nexport const MEDIA_RESOURCES = '+JSON.stringify(entries,null,2)+'\n')
fs.writeFileSync(new URL('../src/reviews.js',import.meta.url),'// Generated by scripts/build-reviewed-content.mjs.\nexport const REVIEWS = '+JSON.stringify(reviews,null,2)+`\nexport function reviewFor(token) { return REVIEWS[token.slug] || null }
export function isCurrent(token) { return REVIEWS[token.slug]?.status === 'verified' && (!token.expiry_date || token.expiry_date >= new Date().toISOString().slice(0,10)) }
export function localizeToken(token, lang) { const r = reviewFor(token); return lang === 'en' && r ? { ...token, ...r.en } : token }
`)
console.log(`Built ${entries.length} media resources; ${Object.keys(reviews).length} reviews.`)
